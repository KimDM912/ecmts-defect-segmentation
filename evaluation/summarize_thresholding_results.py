def group_rows(
    rows: Iterable[dict[str, Any]],
    keys: Sequence[str],
) -> dict[tuple[Any, ...], list[dict[str, Any]]]:
    groups: dict[tuple[Any, ...], list[dict[str, Any]]] = defaultdict(list)
    for row in rows:
        groups[tuple(row[key] for key in keys)].append(row)
    return groups


def configuration_sort_key(dataset: str, backbone: str) -> tuple[int, int]:
    dataset_key = next(
        key for key, display in DATASET_DISPLAY.items() if display == dataset
    )
    backbone_key = next(
        key for key, display in BACKBONE_DISPLAY.items() if display == backbone
    )
    return DATASET_ORDER.index(dataset_key), BACKBONE_ORDER.index(backbone_key)


def image_macro_rows(per_image_rows: list[dict[str, Any]]) -> list[dict[str, Any]]:
    output: list[dict[str, Any]] = []
    groups = group_rows(per_image_rows, ("Dataset", "Backbone", "Method"))

    for (dataset, backbone, method), rows in groups.items():
        record: dict[str, Any] = {
            "Dataset": dataset,
            "Backbone": backbone,
            "Method": method,
            "n_images": len(rows),
        }
        for metric in METRIC_ORDER:
            values = np.asarray([float(row[metric]) for row in rows], dtype=np.float64)
            record[f"Mean_{metric}"] = float(np.mean(values))
            record[f"SD_{metric}"] = (
                float(np.std(values, ddof=1)) if values.size > 1 else 0.0
            )
            record[f"Median_{metric}"] = float(np.median(values))
        output.append(record)

    method_index = {method: index for index, method in enumerate(METHOD_ORDER)}
    output.sort(
        key=lambda row: (
            *configuration_sort_key(str(row["Dataset"]), str(row["Backbone"])),
            method_index[str(row["Method"])],
        )
    )
    return output


def sign_flip_permutation_p(
    difference: np.ndarray,
    iterations: int,
    rng: np.random.Generator,
) -> float:
    """Two-sided paired sign-flip permutation p-value for the mean difference."""
    values = np.asarray(difference, dtype=np.float64)
    values = values[np.isfinite(values)]
    if values.size == 0:
        return float("nan")
    if iterations <= 0:
        raise ValueError("permutation iterations must be positive")

    observed = abs(float(np.mean(values)))
    exceed = 0
    remaining = int(iterations)
    batch_size = min(500, remaining)

    while remaining > 0:
        size = min(batch_size, remaining)
        signs = rng.integers(0, 2, size=(size, values.size), dtype=np.int8)
        signs = signs * 2 - 1
        permuted = np.abs((signs * values).mean(axis=1))
        exceed += int(np.count_nonzero(permuted >= observed - 1e-15))
        remaining -= size

    return float((exceed + 1) / (iterations + 1))


def paired_bootstrap_ci(
    difference: np.ndarray,
    iterations: int,
    rng: np.random.Generator,
    alpha: float,
) -> tuple[float, float]:
    """Percentile CI for the mean paired image-level difference."""
    values = np.asarray(difference, dtype=np.float64)
    values = values[np.isfinite(values)]
    if values.size == 0:
        return float("nan"), float("nan")
    if iterations <= 0:
        raise ValueError("bootstrap iterations must be positive")

    means = np.empty(iterations, dtype=np.float64)
    remaining = int(iterations)
    cursor = 0
    batch_size = min(500, remaining)

    while remaining > 0:
        size = min(batch_size, remaining)
        indices = rng.integers(0, values.size, size=(size, values.size))
        means[cursor : cursor + size] = values[indices].mean(axis=1)
        cursor += size
        remaining -= size

    low, high = np.quantile(means, [alpha / 2.0, 1.0 - alpha / 2.0])
    return float(low), float(high)


def paired_f2_statistics(
    per_image_rows: list[dict[str, Any]],
    *,
    permutation_iterations: int,
    bootstrap_iterations: int,
    alpha: float,
    seed: int,
) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    nested: dict[tuple[str, str, str], dict[str, float]] = defaultdict(dict)
    for row in per_image_rows:
        key = (str(row["Dataset"]), str(row["Backbone"]), str(row["ImageID"]))
        nested[key][str(row["Method"])] = float(row["F2"])

    stats_rows: list[dict[str, Any]] = []
    shapiro_rows: list[dict[str, Any]] = []
    master_rng = np.random.default_rng(seed)

    for dataset_key in DATASET_ORDER:
        dataset = DATASET_DISPLAY[dataset_key]
        for backbone_key in BACKBONE_ORDER:
            backbone = BACKBONE_DISPLAY[backbone_key]
            config = {
                image_id: methods
                for (current_dataset, current_backbone, image_id), methods in nested.items()
                if current_dataset == dataset and current_backbone == backbone
            }
            if not config:
                continue

            for baseline in BASELINE_ORDER:
                paired_values: list[tuple[float, float]] = []
                for image_id in sorted(config):
                    methods = config[image_id]
                    if "ECMTS" not in methods or baseline not in methods:
                        continue
                    ecmts_value = methods["ECMTS"]
                    baseline_value = methods[baseline]
                    if math.isfinite(ecmts_value) and math.isfinite(baseline_value):
                        paired_values.append((ecmts_value, baseline_value))

                if not paired_values:
                    raise RuntimeError(
                        f"No paired F2 values for {dataset}/{backbone}: ECMTS vs {baseline}"
                    )

                paired = np.asarray(paired_values, dtype=np.float64)
                difference = paired[:, 0] - paired[:, 1]

                local_seed = int(
                    master_rng.integers(0, np.iinfo(np.uint32).max)
                )
                rng_permutation = np.random.default_rng(local_seed)
                rng_bootstrap = np.random.default_rng(local_seed ^ 0x9E3779B9)

                p_value = sign_flip_permutation_p(
                    difference,
                    permutation_iterations,
                    rng_permutation,
                )
                ci_low, ci_high = paired_bootstrap_ci(
                    difference,
                    bootstrap_iterations,
                    rng_bootstrap,
                    alpha,
                )

                if difference.size >= 3:
                    with warnings.catch_warnings():
                        warnings.simplefilter("ignore")
                        shapiro_result = shapiro(difference)
                    shapiro_w = float(shapiro_result.statistic)
                    shapiro_p = float(shapiro_result.pvalue)
                    normality = "Normal" if shapiro_p >= alpha else "Not normal"
                else:
                    shapiro_w = float("nan")
                    shapiro_p = float("nan")
                    normality = "Not available"

                delta = float(np.mean(difference))
                significant = bool(math.isfinite(p_value) and p_value < alpha)
                if significant and delta > 0:
                    direction = "ECMTS better"
                elif significant and delta < 0:
                    direction = "ECMTS worse"
                else:
                    direction = "Not significant"

                stats_rows.append(
                    {
                        "Dataset": dataset,
                        "Backbone": backbone,
                        "Metric": "F2",
                        "Baseline": baseline,
                        "n_images": int(difference.size),
                        "ECMTS_Mean": float(np.mean(paired[:, 0])),
                        "Baseline_Mean": float(np.mean(paired[:, 1])),
                        "Delta_F2": delta,
                        "CI95_Low": ci_low,
                        "CI95_High": ci_high,
                        "Permutation_p": p_value,
                        "Sig.": "O" if significant else "X",
                        "Direction": direction,
                    }
                )
                shapiro_rows.append(
                    {
                        "Dataset": dataset,
                        "Backbone": backbone,
                        "Metric": "F2",
                        "Baseline": baseline,
                        "n_images": int(difference.size),
                        "Shapiro_W": shapiro_w,
                        "Shapiro_p": shapiro_p,
                        "Normality": normality,
                    }
                )

    return stats_rows, shapiro_rows


