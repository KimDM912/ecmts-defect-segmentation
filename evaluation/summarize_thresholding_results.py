def excel_value(value: Any) -> Any:
    if isinstance(value, np.generic):
        return value.item()
    if isinstance(value, float) and not math.isfinite(value):
        return None
    return value


def column_width(column: str) -> float:
    explicit = {
        "Dataset": 18,
        "Backbone": 17,
        "Method": 18,
        "Baseline": 18,
        "Metric": 10,
        "n_images": 11,
        "Sig.": 8,
        "Direction": 18,
        "Normality": 15,
    }
    return explicit.get(column, 16)


def number_format(column: str) -> str | None:
    if column == "n_images":
        return "0"
    if column in {"Permutation_p", "Shapiro_p"}:
        return "0.000000"
    if column.startswith(("Mean_", "SD_", "Median_")):
        return "0.000000"
    if column in {
        "ECMTS_Mean",
        "Baseline_Mean",
        "Delta_F2",
        "CI95_Low",
        "CI95_High",
        "Shapiro_W",
    }:
        return "0.000000"
    return None


def write_table_sheet(
    workbook: Workbook,
    sheet_name: str,
    rows: list[dict[str, Any]],
    columns: Sequence[str],
) -> None:
    sheet = workbook.create_sheet(title=sheet_name)
    sheet.sheet_view.showGridLines = False

    sheet.append(list(columns))
    for row in rows:
        sheet.append([excel_value(row.get(column)) for column in columns])

    for cell in sheet[1]:
        cell.fill = HEADER_FILL
        cell.font = Font(bold=True, color="FFFFFF")
        cell.alignment = Alignment(
            horizontal="center",
            vertical="center",
            wrap_text=True,
        )
    sheet.row_dimensions[1].height = 30

    numeric_columns = {
        index
        for index, column in enumerate(columns, start=1)
        if number_format(column) is not None
    }

    for row_cells in sheet.iter_rows(
        min_row=2,
        max_row=max(sheet.max_row, 2),
        min_col=1,
        max_col=len(columns),
    ):
        for index, cell in enumerate(row_cells, start=1):
            cell.border = BODY_BORDER
            cell.alignment = Alignment(
                horizontal="right" if index in numeric_columns else "left",
                vertical="center",
                wrap_text=False,
            )

    for index, column in enumerate(columns, start=1):
        letter = get_column_letter(index)
        sheet.column_dimensions[letter].width = column_width(column)
        format_code = number_format(column)
        if format_code is not None:
            for row_index in range(2, sheet.max_row + 1):
                sheet.cell(row=row_index, column=index).number_format = format_code

    sheet.freeze_panes = "A2"
    sheet.auto_filter.ref = sheet.dimensions
    sheet.print_title_rows = "1:1"
    sheet.page_setup.orientation = "landscape"
    sheet.page_setup.fitToWidth = 1
    sheet.sheet_properties.pageSetUpPr.fitToPage = True

    if rows and "Sig." in columns:
        index = list(columns).index("Sig.") + 1
        letter = get_column_letter(index)
        target_range = f"{letter}2:{letter}{len(rows) + 1}"
        sheet.conditional_formatting.add(
            target_range,
            FormulaRule(
                formula=[f'{letter}2="O"'],
                fill=GREEN_FILL,
                font=Font(bold=True),
            ),
        )
        sheet.conditional_formatting.add(
            target_range,
            FormulaRule(
                formula=[f'{letter}2="X"'],
                fill=GRAY_FILL,
            ),
        )

    if rows and "Direction" in columns:
        index = list(columns).index("Direction") + 1
        letter = get_column_letter(index)
        target_range = f"{letter}2:{letter}{len(rows) + 1}"
        sheet.conditional_formatting.add(
            target_range,
            FormulaRule(
                formula=[f'{letter}2="ECMTS better"'],
                fill=GREEN_FILL,
            ),
        )
        sheet.conditional_formatting.add(
            target_range,
            FormulaRule(
                formula=[f'{letter}2="ECMTS worse"'],
                fill=RED_FILL,
            ),
        )

    if rows and "Normality" in columns:
        index = list(columns).index("Normality") + 1
        letter = get_column_letter(index)
        target_range = f"{letter}2:{letter}{len(rows) + 1}"
        sheet.conditional_formatting.add(
            target_range,
            FormulaRule(
                formula=[f'{letter}2="Not normal"'],
                fill=RED_FILL,
            ),
        )


def build_workbook(
    macro_rows: list[dict[str, Any]],
    stats_rows: list[dict[str, Any]],
    shapiro_rows: list[dict[str, Any]],
) -> Workbook:
    workbook = Workbook()
    workbook.remove(workbook.active)

    write_table_sheet(
        workbook,
        "Image_Macro",
        macro_rows,
        IMAGE_MACRO_COLUMNS,
    )
    write_table_sheet(
        workbook,
        "Stats_F2",
        stats_rows,
        STATS_F2_COLUMNS,
    )
    write_table_sheet(
        workbook,
        "Shapiro_Detail",
        shapiro_rows,
        SHAPIRO_COLUMNS,
    )
    return workbook


# =============================================================================
# Main
# =============================================================================


def main(argv: Sequence[str] | None = None) -> None:
    args = parse_args(argv)
    if not (0.0 < args.alpha < 1.0):
        raise ValueError("alpha must lie strictly between 0 and 1")
    if args.permutation_iters <= 0 or args.bootstrap_iters <= 0:
        raise ValueError("permutation-iters and bootstrap-iters must be positive")

    project_root = args.project_root.expanduser().resolve()
    results_root = (
        args.results_root.expanduser().resolve()
        if args.results_root is not None
        else (project_root / "evaluation" / "results_thresholding").resolve()
    )
    output_path = (
        args.output.expanduser().resolve()
        if args.output is not None
        else (results_root / "thresholding_method_summary.xlsx").resolve()
    )

    print("=" * 100)
    print("[START] Aggregate thresholding results")
    print(f"[RESULTS ROOT] {results_root}")
    print(f"[SEED] {args.seed}")
    print(f"[PERMUTATION ITERATIONS] {args.permutation_iters}")
    print(f"[BOOTSTRAP ITERATIONS] {args.bootstrap_iters}")
    print(f"[ALPHA] {args.alpha}")
    print("[MULTIPLE-COMPARISON CORRECTION] None")
    print("=" * 100)

    per_image_rows, loaded_paths = load_all_results(
        results_root,
        seed=args.seed,
        allow_missing=args.allow_missing,
    )
    print(f"[LOADED FILES] {len(loaded_paths)}")
    print(f"[PER-IMAGE METHOD ROWS] {len(per_image_rows)}")

    macro_rows = image_macro_rows(per_image_rows)
    stats_rows, shapiro_rows = paired_f2_statistics(
        per_image_rows,
        permutation_iterations=args.permutation_iters,
        bootstrap_iterations=args.bootstrap_iters,
        alpha=args.alpha,
        seed=args.seed,
    )

    workbook = build_workbook(macro_rows, stats_rows, shapiro_rows)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    workbook.save(output_path)

    expected_configs = len(loaded_paths)
    print(f"[CONFIGURATIONS] {expected_configs}")
    print(f"[IMAGE_MACRO ROWS] {len(macro_rows)}")
    print(f"[STATS_F2 ROWS] {len(stats_rows)}")
    print(f"[SHAPIRO ROWS] {len(shapiro_rows)}")
    print(f"[OK] Workbook saved: {output_path}")
    print("=" * 100)


if __name__ == "__main__":
    main()
