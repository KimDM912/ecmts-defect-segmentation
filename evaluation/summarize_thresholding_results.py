def read_csv_rows(path: Path) -> list[dict[str, str]]:
    last_error: Exception | None = None
    for encoding in ("utf-8-sig", "utf-8", "cp949"):
        try:
            with path.open("r", encoding=encoding, newline="") as handle:
                return [dict(row) for row in csv.DictReader(handle)]
        except UnicodeDecodeError as exc:
            last_error = exc
    raise RuntimeError(f"Could not decode CSV {path}: {last_error}")


def expected_result_path(
    results_root: Path,
    *,
    dataset: str,
    backbone: str,
    seed: int,
) -> Path:
    return (
        results_root
        / dataset
        / backbone
        / f"seed_{seed}"
        / "per_image_metrics.csv"
    )


def normalize_source_rows(
    raw_rows: list[dict[str, str]],
    *,
    source: Path,
    expected_dataset: str,
    expected_backbone: str,
) -> list[dict[str, Any]]:
    if not raw_rows:
        raise RuntimeError(f"Input CSV is empty: {source}")

    normalized: list[dict[str, Any]] = []
    seen: set[tuple[str, str]] = set()

    for row_number, row in enumerate(raw_rows, start=2):
        dataset_raw = first_present(
            row,
            ("dataset", "Dataset", "dataset_display_name", "DatasetDisplayName"),
        )
        backbone_raw = first_present(row, ("backbone", "Backbone"))
        method_raw = first_present(row, ("method", "Method"))
        image_raw = first_present(row, ("image_id", "ImageID", "image", "Image"))

        dataset = canonical_dataset(dataset_raw)
        backbone = canonical_backbone(backbone_raw)
        method = canonical_method(method_raw)
        image_id = str(image_raw).strip() if image_raw is not None else ""

        if dataset is None:
            raise ValueError(
                f"Unknown dataset at {source}, row {row_number}: {dataset_raw!r}"
            )
        if backbone is None:
            raise ValueError(
                f"Unknown backbone at {source}, row {row_number}: {backbone_raw!r}"
            )
        if method is None:
            raise ValueError(
                f"Unknown method at {source}, row {row_number}: {method_raw!r}"
            )
        if not image_id:
            raise ValueError(f"Missing image ID at {source}, row {row_number}")
        if dataset != expected_dataset or backbone != expected_backbone:
            raise ValueError(
                "CSV content does not match its result directory: "
                f"expected={expected_dataset}/{expected_backbone}, "
                f"row={dataset}/{backbone}, source={source}, row={row_number}"
            )

        unique_key = (image_id, method)
        if unique_key in seen:
            raise RuntimeError(
                f"Duplicate image-method row in {source}: image={image_id!r}, method={method}"
            )
        seen.add(unique_key)

        normalized.append(
            {
                "DatasetKey": dataset,
                "Dataset": DATASET_DISPLAY[dataset],
                "BackboneKey": backbone,
                "Backbone": BACKBONE_DISPLAY[backbone],
                "ImageID": image_id,
                "Method": method,
                "Precision": finite_float(
                    first_present(row, ("precision", "Precision")),
                    field="Precision",
                    source=source,
                    row_number=row_number,
                ),
                "Recall": finite_float(
                    first_present(row, ("recall", "Recall")),
                    field="Recall",
                    source=source,
                    row_number=row_number,
                ),
                "F2": finite_float(
                    first_present(row, ("f2", "F2")),
                    field="F2",
                    source=source,
                    row_number=row_number,
                ),
            }
        )

    return normalized


def validate_configuration_rows(
    rows: list[dict[str, Any]],
    *,
    dataset: str,
    backbone: str,
    source: Path,
) -> None:
    method_images: dict[str, set[str]] = defaultdict(set)
    for row in rows:
        method_images[str(row["Method"])].add(str(row["ImageID"]))

    missing_methods = [method for method in METHOD_ORDER if method not in method_images]
    if missing_methods:
        raise RuntimeError(
            f"Missing methods in {source}: {missing_methods}. "
            f"Required methods={list(METHOD_ORDER)}"
        )

    reference = method_images["ECMTS"]
    if not reference:
        raise RuntimeError(f"No ECMTS images found in {source}")

    mismatches: list[str] = []
    for method in METHOD_ORDER:
        current = method_images[method]
        if current != reference:
            missing = sorted(reference - current)[:5]
            extra = sorted(current - reference)[:5]
            mismatches.append(
                f"{method}: n={len(current)}, missing={missing}, extra={extra}"
            )
    if mismatches:
        raise RuntimeError(
            "Method image sets are not identical for "
            f"{dataset}/{backbone} in {source}:\n  " + "\n  ".join(mismatches)
        )


def load_all_results(
    results_root: Path,
    *,
    seed: int,
    allow_missing: bool,
) -> tuple[list[dict[str, Any]], list[Path]]:
    all_rows: list[dict[str, Any]] = []
    loaded_paths: list[Path] = []
    missing_paths: list[Path] = []

    for dataset in DATASET_ORDER:
        for backbone in BACKBONE_ORDER:
            source = expected_result_path(
                results_root,
                dataset=dataset,
                backbone=backbone,
                seed=seed,
            )
            if not source.is_file():
                missing_paths.append(source)
                continue

            rows = normalize_source_rows(
                read_csv_rows(source),
                source=source,
                expected_dataset=dataset,
                expected_backbone=backbone,
            )
            validate_configuration_rows(
                rows,
                dataset=dataset,
                backbone=backbone,
                source=source,
            )
            all_rows.extend(rows)
            loaded_paths.append(source)

    if missing_paths and not allow_missing:
        formatted = "\n  - ".join(str(path) for path in missing_paths)
        raise FileNotFoundError(
            "The following required result files are missing:\n  - " + formatted
        )
    if not all_rows:
        raise RuntimeError(f"No per-image result rows were loaded from {results_root}")

    return all_rows, loaded_paths


