def token(value: object) -> str:
    return "".join(character for character in str(value).lower() if character.isalnum())


def first_present(row: dict[str, Any], names: Sequence[str]) -> Any:
    for name in names:
        if name in row and str(row[name]).strip() != "":
            return row[name]
    return None


def canonical_dataset(value: object) -> str | None:
    return DATASET_ALIASES.get(token(value))


def canonical_backbone(value: object) -> str | None:
    return BACKBONE_ALIASES.get(token(value))


def canonical_method(value: object) -> str | None:
    return METHOD_ALIASES.get(token(value))


def finite_float(value: object, *, field: str, source: Path, row_number: int) -> float:
    try:
        result = float(str(value).strip())
    except (TypeError, ValueError) as exc:
        raise ValueError(
            f"Invalid {field} at {source}, row {row_number}: {value!r}"
        ) from exc
    if not math.isfinite(result):
        raise ValueError(
            f"Non-finite {field} at {source}, row {row_number}: {value!r}"
        )
    return result


