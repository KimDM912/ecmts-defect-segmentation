"""Aggregate thresholding evaluation results into one Excel workbook.

Expected input layout
---------------------
<results-root>/
    severstal/resnet18/seed_2026/per_image_metrics.csv
    severstal/resnet34/seed_2026/per_image_metrics.csv
    severstal/efficientnet_b0/seed_2026/per_image_metrics.csv
    kolektor/resnet18/seed_2026/per_image_metrics.csv
    ...
    magnetic/efficientnet_b0/seed_2026/per_image_metrics.csv

The source CSVs are generated by ``evaluate_thresholding.py``. The method name
``Proposed`` is renamed to ``ECMTS`` in the workbook.

Workbook sheets
---------------
1. Image_Macro
   Image-wise macro mean, sample SD, and median for Precision, Recall, and F2.

2. Stats_F2
   ECMTS versus each baseline using paired image-level F2 values:
   - two-sided paired sign-flip permutation test;
   - paired image bootstrap percentile 95% confidence interval;
   - 10,000 iterations for both procedures by default;
   - no multiple-comparison correction.

3. Shapiro_Detail
   Shapiro-Wilk normality test on paired image-level F2 differences
   (ECMTS minus baseline).

Default execution from the repository root
------------------------------------------
python evaluation/main_experiment/summarize_thresholding_results.py

Dependencies
------------
numpy, scipy, openpyxl
"""

